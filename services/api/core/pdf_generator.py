import datetime

class ReportGenerator:
    """
    Utility to generate downloadable reports (PDF, CSV, or HTML).
    Fulfills the requirement for crop insurers or agronomist sharing.
    """
    
    def generate_farm_summary_html(self, farm_name: str, stats: dict, recent_alerts: list) -> str:
        """
        Generates an HTML string that can be sent to the frontend or converted to PDF.
        """
        today = datetime.datetime.now().strftime("%Y-%m-%d")
        
        alerts_html = ""
        if not recent_alerts:
            alerts_html = "<p>No recent critical alerts. Your farm is healthy!</p>"
        else:
            alerts_html = "<ul>"
            for alert in recent_alerts:
                alerts_html += f"<li><strong>{alert.get('date')}</strong>: {alert.get('message')}</li>"
            alerts_html += "</ul>"

        html_content = f"""
        <html>
            <head>
                <style>
                    body {{ font-family: Arial, sans-serif; padding: 40px; color: #333; }}
                    h1 {{ color: #2E7D32; border-bottom: 2px solid #2E7D32; padding-bottom: 10px; }}
                    .stats-box {{ background: #f1f8e9; padding: 20px; border-radius: 8px; margin-bottom: 20px; }}
                    .alerts-section {{ margin-top: 30px; }}
                    .footer {{ margin-top: 50px; font-size: 12px; color: #777; text-align: center; }}
                </style>
            </head>
            <body>
                <h1>AgriGuard AI - Farm Health Report</h1>
                <p><strong>Farm Name:</strong> {farm_name}</p>
                <p><strong>Generated On:</strong> {today}</p>
                
                <div class="stats-box">
                    <h2>Key Metrics</h2>
                    <p>Total Fields: {stats.get('total_fields', 0)}</p>
                    <p>Total Area: {stats.get('total_area_acres', 0)} Acres</p>
                    <p>Healthy Fields: {stats.get('disease_rates', {{}}).get('healthy_percentage', 100)}%</p>
                </div>
                
                <div class="alerts-section">
                    <h2>Recent AI Health Alerts</h2>
                    {alerts_html}
                </div>
                
                <div class="footer">
                    <p>Generated by AgriGuard AI Platform. This report is for informational purposes.</p>
                </div>
            </body>
        </html>
        """
        return html_content

report_generator = ReportGenerator()
